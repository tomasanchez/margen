"""Frozen Pydantic commands for the receivables cluster (ADR-204, ADR-206, ADR-130).

Commands are immutable, boundary-agnostic requests to change state. They carry input
fields only: ``id``, ``created_at`` and identity of created rows are server-managed and
generated by the handler, never supplied by the caller (ADR-026). Money is ``Decimal``
(ADR-025), ARS-only for v1. ``user_id`` is the authenticated owner the entrypoint stamps
before dispatch so every person — and, through it, every item and payment — is owned from
creation (ADR-130).

The :class:`Person` is the aggregate root; items and payments key off it, so every item,
cuota and payment write command carries the ``person_id``: the handler locks that person
first — serializing the writes on one person's receivables — and refuses an item that belongs
to someone else (ADR-130, ADR-111). A payment is recorded together with its allocations across
items in one command so the settlement is atomic (ADR-206).

An item may be split into cuotas through an :class:`InstallmentPlanInput` (ADR-214, ADR-216)
and may reference the expense it came from through ``source_transaction_id`` — a reference
only, never a netting (ADR-217, ADR-219).
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal
from typing import Self
from uuid import UUID

from pydantic import Field, model_validator

from margen_api.domain.messages import Command, Message
from margen_api.domain.models.receivable import InstallmentAdjustment, InstallmentPlan
from margen_api.domain.models.value_objects import PaymentSource

# The longest cuota plan accepted (ten years of monthly cuotas): a sanity bound on how many
# schedule rows one request may generate, well past any real personal IOU.
MAX_INSTALLMENTS = 120


class InstallmentPlanInput(Message):
    """The cuota plan the owner asks for: how many cuotas, and when the first falls due (ADR-216).

    The domain derives the schedule from it — the even split of the item total with the
    remainder on the last cuota, due monthly from ``first_due_on``.
    """

    count: int = Field(ge=2, le=MAX_INSTALLMENTS)
    first_due_on: date

    def to_plan(self) -> InstallmentPlan:
        """Translate the input into the domain :class:`InstallmentPlan`."""
        return InstallmentPlan(count=self.count, first_due_on=self.first_due_on)


class InstallmentAdjustmentInput(Message):
    """A tweak to one cuota of a new plan: its amount and/or due date (ADR-216).

    ``None`` keeps the even-split value; the domain checks the index exists in the plan.
    """

    index: int = Field(ge=1)
    amount: Decimal | None = Field(default=None, gt=Decimal(0))
    due_on: date | None = None

    def to_adjustment(self) -> InstallmentAdjustment:
        """Translate the input into the domain :class:`InstallmentAdjustment`."""
        return InstallmentAdjustment(index=self.index, amount=self.amount, due_on=self.due_on)


class NewInstallmentPlanInput(InstallmentPlanInput):
    """The cuota plan of an item being created, with optional per-cuota tweaks (ADR-216).

    The tweaks are applied in the same write that creates the item, so a plan with interest on
    a cuota is never visible half-applied.
    """

    cuotas: tuple[InstallmentAdjustmentInput, ...] = ()

    def to_adjustments(self) -> tuple[InstallmentAdjustment, ...]:
        """Translate the per-cuota tweaks into domain :class:`InstallmentAdjustment` values."""
        return tuple(cuota.to_adjustment() for cuota in self.cuotas)


class CreatePerson(Command):
    """Request to create a new debtor the owner tracks receivables against (ADR-204, ADR-130).

    The handler generates ``id`` and ``created_at`` and applies the domain invariant
    (non-empty name) via the aggregate.
    """

    user_id: str
    name: str = Field(min_length=1)


class RenamePerson(Command):
    """Request to rename an existing person (ADR-204, ADR-130).

    The handler loads the person by ``id`` **scoped to ``user_id``** (a foreign owner's id
    is not found, ADR-111), applies the new name and re-runs the invariant. Ownership,
    identity and ``created_at`` are never changed.
    """

    id: UUID
    user_id: str
    name: str = Field(min_length=1)


class DeletePerson(Command):
    """Request to delete a person by identity (ADR-204, ADR-130).

    The handler scopes the delete by ``user_id`` so a cross-tenant delete removes nothing
    and surfaces a not-found (404, ADR-111). The database cascades the person's items and
    payments (and their allocations) away (ADR-208).
    """

    id: UUID
    user_id: str


class AddReceivableItem(Command):
    """Request to add an itemized debt to one of the owner's people (ADR-204, ADR-130).

    The handler verifies the person exists for the owner (else 404, ADR-111), then
    generates ``id`` and ``created_at`` and applies the domain invariant (positive
    amount). ``detail`` is the optional free-text justification, trimmed to ``None`` when
    blank by the aggregate.

    ``installments`` splits the debt into cuotas, optionally tweaking some of them
    (ADR-214, ADR-216); ``None`` keeps it flat. ``source_transaction_id`` optionally links the
    expense the debt came from (ADR-217): the handler verifies it is one of the owner's own
    ``kind='expense'`` transactions (else 404).

    ``item_id`` is an optional client-generated identity that makes the creation idempotent —
    a deliberate exception to server-generated ids (ADR-026): re-sending the same id with the
    same terms replays the creation instead of duplicating the debt, while the same id with
    other terms (or an id already used elsewhere) is a conflict.
    """

    user_id: str
    person_id: UUID
    occurred_on: date
    amount: Decimal = Field(gt=Decimal(0))
    detail: str | None = None
    installments: NewInstallmentPlanInput | None = None
    source_transaction_id: UUID | None = None
    item_id: UUID | None = None


class EditReceivableItem(Command):
    """Request to patch an existing receivable item (ADR-204, ADR-130).

    Every mutable field is optional; ``None`` means "leave unchanged". The handler locks the
    person, loads the item by ``id`` **scoped to the owner and that person** (ADR-111),
    applies the present fields, and re-runs invariants. The item's ``person_id``,
    identity and ``created_at`` are never changed.

    The cuota plan and the expense link are tri-state (ADR-216, ADR-217): ``installments`` sets
    or re-shapes the plan and ``remove_installments`` turns the item back into a flat one,
    while ``source_transaction_id`` links an expense and ``unlink_source_transaction`` drops the
    link; leaving both of a pair unset keeps the current state. Re-shaping the plan (a new
    count, first due date or total on an installment item, or a conversion either way) is
    refused while the item has allocations or pardons (ADR-216).
    """

    id: UUID
    user_id: str
    person_id: UUID
    occurred_on: date | None = None
    amount: Decimal | None = Field(default=None, gt=Decimal(0))
    detail: str | None = None
    installments: InstallmentPlanInput | None = None
    remove_installments: bool = False
    source_transaction_id: UUID | None = None
    unlink_source_transaction: bool = False

    @model_validator(mode="after")
    def _reject_contradictions(self) -> Self:
        """Refuse a patch that both sets and clears the same tri-state field."""
        if self.installments is not None and self.remove_installments:
            msg = "a patch cannot both set and remove the installment plan"
            raise ValueError(msg)
        if self.source_transaction_id is not None and self.unlink_source_transaction:
            msg = "a patch cannot both link and unlink the source transaction"
            raise ValueError(msg)
        return self


class DeleteReceivableItem(Command):
    """Request to delete a receivable item by identity (ADR-204, ADR-130).

    The handler scopes the delete to the owner and the person (locked first) so a
    cross-tenant delete — or one aimed at another person's item — removes nothing and
    surfaces a not-found (404, ADR-111). The database cascades the item's allocations away
    (ADR-208).
    """

    id: UUID
    user_id: str
    person_id: UUID


class SetReceivableItemPardon(Command):
    """Request to pardon or un-pardon a receivable item (ADR-210, ADR-130).

    A single reversible toggle: ``pardoned=True`` forgives the item (stamping
    ``pardoned_at`` with the moment of forgiveness) so it drops out of the person's
    outstanding and is no longer a valid allocation target (amending ADR-206), while
    ``pardoned=False`` restores it (clearing ``pardoned_at``). Distinct from
    :class:`DeleteReceivableItem`, which permanently removes the row — a pardon keeps the
    item so the shareable statement can show it as "covered by you" (amending ADR-209).

    The handler locks the person and loads the item by ``id`` **scoped to the owner and that
    person** (a foreign owner's id is not found, ADR-111), sets or clears the pardon, and
    preserves ``person_id``, ``occurred_on``, ``amount``, ``detail``, identity and
    ``created_at``.
    """

    id: UUID
    user_id: str
    person_id: UUID
    pardoned: bool


class EditReceivableInstallment(Command):
    """Request to edit one cuota's amount and/or due date (ADR-216, ADR-130).

    Models interest or a recargo applied after the fact. The handler locks the person, loads
    the item scoped to the owner and that person (404 otherwise, ADR-111), edits the cuota at
    ``index`` (404 when there is none) and re-derives the item amount as the sum of its cuotas.
    ``None`` leaves a field unchanged. Allowed even when the plan already has allocations — only
    the plan's shape is locked — but never below what was already paid toward the cuota.
    """

    item_id: UUID
    user_id: str
    person_id: UUID
    index: int = Field(ge=1)
    amount: Decimal | None = Field(default=None, gt=Decimal(0))
    due_on: date | None = None


class SetReceivableInstallmentPardon(Command):
    """Request to pardon or un-pardon a single cuota of an installment item (ADR-221, ADR-130).

    The cuota-grain twin of :class:`SetReceivableItemPardon`: ``pardoned=True`` stamps the
    cuota's ``pardoned_at`` (forgiving just that due), ``pardoned=False`` clears it. Forgiving
    the whole remaining plan goes through :class:`SetReceivableItemPardon` on the item.
    """

    item_id: UUID
    user_id: str
    person_id: UUID
    index: int = Field(ge=1)
    pardoned: bool


class AllocationInput(Message):
    """One slice of a payment applied to a specific item, as supplied by the caller (ADR-206).

    A nested value inside :class:`RecordReceivablePayment`; the handler turns each into a
    :class:`~margen_api.domain.models.receivable.ReceivableAllocation` once the payment's
    identity exists. ``amount`` is a positive ARS magnitude (ADR-025). ``installment_id``
    names the cuota the slice settles: required for an item with a schedule, forbidden for a
    flat one (ADR-221, ADR-223).
    """

    item_id: UUID
    amount: Decimal = Field(gt=Decimal(0))
    installment_id: UUID | None = None


class RecordReceivablePayment(Command):
    """Request to record an incoming payback and allocate it across items (ADR-204, ADR-206).

    The handler verifies the person exists for the owner (else 404), verifies every
    allocation targets one of that person's items (else 404), and enforces the two
    settlement rules of ADR-206:

    * The allocations may not sum to more than the payment's own ``amount`` — a true
      invariant violation (``422``).
    * When the allocations would drive the person's outstanding balance below zero, the
      handler raises an overpayment **warning** unless ``allow_overpayment`` is set, so
      the API layer can confirm the credit with the user rather than silently clamping or
      going negative.

    ``source``/``matched_income_transaction_id`` record whether the payback was typed by
    hand (``manual``) or confirmed from a fuzzy income match (``matched_income``, ADR-207);
    the confirm flow that produces the latter lives in a separate slice.

    ``as_of`` is the date the overpayment threshold is assessed on: only cuotas due by then
    count as outstanding (ADR-215). The HTTP boundary stamps its injected "today"; when a
    caller omits it the handler uses the server's current UTC date.
    """

    user_id: str
    person_id: UUID
    occurred_on: date
    amount: Decimal = Field(gt=Decimal(0))
    allocations: tuple[AllocationInput, ...] = Field(min_length=1)
    source: PaymentSource = PaymentSource.MANUAL
    matched_income_transaction_id: UUID | None = None
    allow_overpayment: bool = False
    as_of: date | None = None
